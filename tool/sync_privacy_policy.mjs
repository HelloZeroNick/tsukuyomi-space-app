// Copy reviewed website policy into a synchronous native document for offline access.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(process.argv[2] || '../tsukuyomi-space');
const source = JSON.parse(fs.readFileSync(path.join(root, 'shared/privacy-policy.json'), 'utf8'));
const output = `// Generated by tool/sync_privacy_policy.mjs. Edit the website shared policy.\nconst privacyPolicy = <String, dynamic>${JSON.stringify(source, null, 2).replace(/\$/g, '\\$')};\n`;
fs.writeFileSync('lib/core/privacy_policy.dart', output);
console.log(`Privacy policy ${source.version} synchronized.`);
